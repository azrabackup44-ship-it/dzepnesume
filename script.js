const amountsByMode = {
  once: [390, 1000, 2500],
  monthly: [590, 990, 1900],
  yearly: [3900, 5900, 9900],
};
let currentMode = "once",
  currentAmount = 390,
  currentLang = location.pathname.startsWith("/en") ? "en" : "sr";
const money = new Intl.NumberFormat("sr-RS");
function renderAmounts() {
  const wrap = document.querySelector("#amounts");
  wrap.innerHTML = amountsByMode[currentMode]
    .map(
      (value, index) =>
        `<button class="amount-button ${index === 0 ? "active" : ""}" data-value="${value}">${money.format(value)} <small>RSD</small></button>`,
    )
    .join("");
  currentAmount = amountsByMode[currentMode][0];
  wrap.querySelectorAll("button").forEach((btn) =>
    btn.addEventListener("click", () => {
      wrap
        .querySelectorAll("button")
        .forEach((x) => x.classList.remove("active"));
      btn.classList.add("active");
      currentAmount = Number(btn.dataset.value);
      document.querySelector("#customAmount").value = "";
    }),
  );
}
function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = translations[lang][el.dataset.i18n];
    if (value) el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const value = translations[lang][el.dataset.i18nHtml];
    if (value) el.innerHTML = value;
  });
  document.querySelectorAll(".language-button").forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-pressed", String(active));
  });
  history.replaceState({}, "", lang === "en" ? "/en/" : "/");
}
document.querySelectorAll(".support-tab").forEach((tab) =>
  tab.addEventListener("click", () => {
    document.querySelectorAll(".support-tab").forEach((x) => {
      x.classList.remove("active");
      x.setAttribute("aria-selected", "false");
    });
    tab.classList.add("active");
    tab.setAttribute("aria-selected", "true");
    currentMode = tab.dataset.mode;
    renderAmounts();
  }),
);
document.querySelector("#customAmount").addEventListener("input", (e) => {
  if (e.target.value) {
    currentAmount = Number(e.target.value);
    document
      .querySelectorAll(".amount-button")
      .forEach((x) => x.classList.remove("active"));
  }
});
const dialog = document.querySelector("#supportDialog");
document
  .querySelector("#supportButton")
  .addEventListener("click", () => dialog.showModal());
document
  .querySelector("#closeDialog")
  .addEventListener("click", () => dialog.close());
document
  .querySelectorAll(".language-button")
  .forEach((btn) =>
    btn.addEventListener("click", () => setLanguage(btn.dataset.lang)),
  );
const menu = document.querySelector("#mainNav"),
  toggle = document.querySelector("#menuToggle");
toggle.addEventListener("click", () => {
  const open = menu.classList.toggle("open");
  toggle.setAttribute("aria-expanded", String(open));
  document.body.classList.toggle("menu-open", open);
});
menu.querySelectorAll("a").forEach((a) =>
  a.addEventListener("click", () => {
    menu.classList.remove("open");
    document.body.classList.remove("menu-open");
    toggle.setAttribute("aria-expanded", "false");
  }),
);
const header = document.querySelector("#siteHeader");
addEventListener(
  "scroll",
  () => header.classList.toggle("scrolled", scrollY > 24),
  { passive: true },
);
const cookies = document.querySelector("#cookieBanner");
if (!localStorage.getItem("dz_cookie_choice"))
  setTimeout(() => cookies.classList.add("visible"), 700);
function closeCookies(choice) {
  localStorage.setItem("dz_cookie_choice", choice);
  cookies.classList.remove("visible");
}
document
  .querySelector("#acceptCookies")
  .addEventListener("click", () => closeCookies("all"));
document
  .querySelector("#rejectCookies")
  .addEventListener("click", () => closeCookies("necessary"));
document
  .querySelector("#openCookies")
  .addEventListener("click", () => cookies.classList.add("visible"));
